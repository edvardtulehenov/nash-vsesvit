// Плавний перехід між сценами
function changeScene(currentScene, nextScene) {
    if (!currentScene || !nextScene || currentScene === nextScene) {
        return;
    }

    // Захист від повторного натискання під час переходу
    if (currentScene.classList.contains("is-leaving")) {
        return;
    }

    currentScene.classList.remove("is-arriving");
    currentScene.classList.add("is-leaving");

    // Чекаємо, поки поточна сцена плавно згасне
    setTimeout(() => {
        currentScene.hidden = true;
        currentScene.classList.remove("is-leaving");

        nextScene.hidden = false;
        nextScene.classList.remove("is-arriving");

        // Перезапускаємо анімацію появи нової сцени
        void nextScene.offsetWidth;
        nextScene.classList.add("is-arriving");

        window.scrollTo({
            top: 0,
            behavior: "auto"
        });
    }, 700);
}

// При першому відкритті показуємо першу сцену
if (intro && universe && letterScene) {
    intro.hidden = false;
    universe.hidden = true;
    letterScene.hidden = true;
}

// Перша сцена -> друга сцена
if (startButton && intro && universe) {
    startButton.addEventListener("click", () => {
        changeScene(intro, universe);
    });
}

