// Розгортання сувою
const scrollButton = document.getElementById("scrollButton");
const scrollMessage = document.getElementById("scrollMessage");
const scrollHint = document.getElementById("scrollHint");

let scrollCloseTimer;

if (scrollButton && scrollMessage) {
    scrollButton.addEventListener("click", () => {
        const isOpening = !scrollButton.classList.contains("is-open");

        clearTimeout(scrollCloseTimer);

        if (isOpening) {
            scrollMessage.hidden = false;

            // Даємо браузеру показати початковий стан
            requestAnimationFrame(() => {
                scrollButton.classList.add("is-open");
            });

            scrollButton.setAttribute("aria-expanded", "true");
            scrollButton.setAttribute("aria-label", "Згорнути сувій");

            if (scrollHint) {
                scrollHint.textContent = "Твоє послання зі зірок 💜";
            }
        } else {
            scrollButton.classList.remove("is-open");
            scrollButton.setAttribute("aria-expanded", "false");
            scrollButton.setAttribute("aria-label", "Розгорнути сувій");

            if (scrollHint) {
                scrollHint.textContent =
                    "Натисни на сувій, щоб розгорнути його ✨";
            }

            // Ховаємо текст після завершення згортання
            scrollCloseTimer = setTimeout(() => {
                scrollMessage.hidden = true;
            }, 1700);
        }
    });
}
