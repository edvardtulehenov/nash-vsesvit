const openedMemories = new Set();

document.querySelectorAll(".memory-star").forEach((star) => {
    star.style.setProperty(
        "--brightness",
        (0.4 + Math.random() * 0.6).toFixed(2)
    );

    star.addEventListener("click", () => {
        const index = Number(star.dataset.memory);
        const memoryCard = document.getElementById("memory-card");

        if (memories[index] !== undefined && memoryCard) {
            memoryCard.textContent = memories[index];
            openedMemories.add(index);
        }

        if (openedMemories.size === 7 && finalStar) {
            finalStar.hidden = false;
        }
    });
});

